"""Writes RealMags' cfg patches from table.toml. Run it, then `zonepak check` and `build`."""
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
GAME_DATA = HERE / 'cfg' / 'GameData'
DLC_DATA = HERE / 'cfg' / 'DLCGameData'
DLCS = ('DLC1',)
HEADER = '// Generated by generate.py from table.toml.'


def effect_sid(owner: str) -> str:
    return f'RealMags_Capacity_{owner}'


def upgrade_sid(weapon: str) -> str:
    return f'RealMags_Hidden_{weapon}'


def effect(sid: str, percent: int) -> list[str]:
    # The fully spelled-out form was verified in-game on 2026-11-02 (Gambit +25% read 15/21).
    # A refkey to a vanilla effect from a patch file is not verified.
    sign = 'Positive' if percent > 0 else 'Negative'
    return [f'{sid} : struct.begin',
            f'   SID = {sid}',
            '   EffectLevel = EEffectLevel::Low',
            '   Text =',
            '   LocalizationSID = Empty',
            '   Hint = false',
            "   Icon = Texture2D'/Game/GameLite/FPS_Game/UI/UIIcons/EffectNone_Texture.EffectNone_Texture'",
            '   Duration = 0.f',
            '   DelayMin = 0.f',
            '   DelayMax = 0.f',
            '   Charges = 0',
            '   TimePerChargeMin = 1.f',
            '   TimePerChargeMax = 1.f',
            '   Type = EEffectType::AmmoCapacity',
            f'   ValueMin = {percent}%',
            f'   ValueMax = {percent}%',
            '   ValueProviderSID = Empty',
            "   AssetPath = '/None.None'",
            '   bIsPermanent = true',
            '   bIsSmooth = true',
            '   DuplicationType = EDuplicateResolveType::KeepAll',
            '   InstantFirstCharge = false',
            f'   Positive = EBeneficial::{sign}',
            '   AttachmentItemPrototypeSID = Empty',
            '   EffectCurvePath =',
            '   IsCurvePercent = false',
            '   ShouldPauseByDialog = true',
            '   DialogIntensityMultiplier = 1.0',
            '   DamageType = empty',
            '   DamageSource = empty',
            'struct.end']


def hidden_upgrade(sid: str, upgrade_id: int, effect: str) -> list[str]:
    # Copied from the in-game-verified 2026-11-02 test upgrade. It is in no weapon's upgrade tree,
    # so it only takes effect through PreinstalledUpgrades.
    empty_list = ['struct.begin', '      [0] = empty', '   struct.end']
    empty_var = ['struct.begin', '      [0] : struct.begin', '         GlobalVariableSID = empty',
                 '         Value = 0.0', '      struct.end', '   struct.end']
    lines = [f'{sid} : struct.begin',
             f'   ID = {upgrade_id}',
             f'   SID = {sid}',
             '   Text =',
             '   Hint =',
             "   Image = Texture2D'/Game/GameLite/FPS_Game/UIRemaster/UITextures/Inventory/T_xleb.T_xleb'",
             "   Icon = Texture2D'/Game/GameLite/FPS_Game/UIRemaster/UITextures/PDA/Upgrades/T_mod_icon_m.T_mod_icon_m'",
             '   BaseCost = 0',
             '   HorizontalPosition = 0',
             '   VerticalPosition = EUpgradeVerticalPosition::None',
             '   DiscountCoefficient = 0.f',
             '   RepairCostModifier = 0.2f',
             '   IsModification = false',
             '   HiddenWihoutItem = false']
    lines += ['   AttachPrototypeSIDs : ' + empty_list[0], *empty_list[1:]]
    lines += ["   UpgradeSound = AkAudioEvent''",
              "   UpgradeModificationSound = AkAudioEvent''",
              "   UpgradeCancelSound = AkAudioEvent''",
              '   UpgradeTargetPart = EUpgradeTargetPartType::None',
              '   EffectPrototypeSIDs : struct.begin',
              f'      [0] = {effect}',
              '   struct.end']
    for key in ('RequiredUpgradePrototypeSIDs', 'RequiredItemPrototypeSIDs', 'BlockingUpgradePrototypeSIDs',
                'InterchangeableUpgradePrototypeSIDs'):
        lines += [f'   {key} : ' + empty_list[0], *empty_list[1:]]
    for key in ('RequiredGlobalVariables', 'BlockingGlobalVariables'):
        lines += [f'   {key} : ' + empty_var[0], *empty_var[1:]]
    lines += ['   Skills : ' + empty_list[0], *empty_list[1:],
              '   ConnectionLines : struct.begin', '      [0] = EConnectionLineState::None', '   struct.end',
              'struct.end']
    return lines


def whole(name: str, value) -> int:
    if type(value) is not int:
        raise SystemExit(f'table.toml: {name} must be a whole number')
    return value


def item_patches(section: dict, prefix: str, effects: list[str], upgrades: list[str]) -> list[str]:
    items = [HEADER]
    for sid, max_ammo in section.get('magazines', {}).items():
        items += [f'{sid} : struct.begin {{bpatch}}',
                  '   Magazine : struct.begin {bpatch}',
                  f'      MaxAmmo = {whole(f"{prefix}magazines.{sid}", max_ammo)}',
                  '   struct.end',
                  'struct.end']
    for weapon, row in section.get('hidden', {}).items():
        percent = whole(f'{prefix}hidden.{weapon}.percent', row.get('percent'))
        upgrade_id = whole(f'{prefix}hidden.{weapon}.id', row.get('id'))
        # DLC1 ships no UpgradePrototypes or effects of its own for these, so the new structs always go in
        # the base tables, and only the weapon patch goes under the DLC root.
        effects += effect(effect_sid(weapon), percent)
        upgrades += hidden_upgrade(upgrade_sid(weapon), upgrade_id, effect_sid(weapon))
        items += [f'{weapon} : struct.begin {{bpatch}}',
                  '   PreinstalledUpgrades : struct.begin {bpatch}',
                  f'      [0] = {upgrade_sid(weapon)}',
                  '   struct.end',
                  'struct.end']
    return items


def generate(table: dict) -> dict[Path, str]:
    effects, upgrades = [HEADER], [HEADER]
    items = item_patches(table, '', effects, upgrades)
    dlc_items = {dlc: item_patches(table[dlc], f'{dlc}.', effects, upgrades) for dlc in DLCS if dlc in table}
    for upgrade, row in table.get('upgrades', {}).items():
        percent = whole(f'upgrades.{upgrade}.percent', row.get('percent'))
        index = whole(f'upgrades.{upgrade}.index', row.get('index'))
        effects += effect(effect_sid(upgrade), percent)
        upgrades += [f'{upgrade} : struct.begin {{bpatch}}',
                     '   EffectPrototypeSIDs : struct.begin {bpatch}',
                     f'      [{index}] = {effect_sid(upgrade)}',
                     '   struct.end',
                     'struct.end']
    files = {GAME_DATA / 'ItemPrototypes': items, GAME_DATA / 'EffectPrototypes': effects,
             GAME_DATA / 'UpgradePrototypes': upgrades}
    files.update({DLC_DATA / dlc / 'ItemPrototypes': lines for dlc, lines in dlc_items.items()})
    return {folder / 'RealMags.cfg': ''.join(line + '\r\n' for line in lines)
            for folder, lines in files.items() if len(lines) > 1}


def main() -> None:
    outputs = generate(tomllib.loads((HERE / 'table.toml').read_text(encoding='utf-8')))
    for stale in [*GAME_DATA.glob('*/RealMags.cfg'), *DLC_DATA.glob('*/*/RealMags.cfg')]:
        if stale not in outputs:
            stale.unlink()
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode('utf-8'))
        print(f'wrote {path.relative_to(HERE).as_posix()}')


if __name__ == '__main__':
    main()
